#!/usr/bin/env python
"""Emit every LaTeX results table in paper/ from the result files, never from a report.

    python scripts/paper/gen_tables.py

HOUSE RULE, inherited from paper_modularity/main.tex and kept deliberately: **no number is typed
into a .tex by hand.** Each table below is generated from a JSON under `results/analysis/`, which
is itself generated from the per-cell parquets. The reports in `docs/` and `MASTER_REPORT.md` are
an index of where to look, not a source; where a report and a result file disagree, the file wins.

Every emitted file carries a header naming the JSON it came from and the generating script, so a
table in the paper can be traced back to a cell in two hops.

A missing input is NOT filled in and is NOT skipped silently: the table emits \\pending in the
affected cells and the script reports it on stderr, so `make audit` (grep for \\pending) still
sees the hole.
"""
from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results" / "analysis"
OUT = ROOT / "paper" / "tables"
PENDING = r"\pending"


def load(rel: str):
    p = RES / rel
    if not p.exists():
        print(f"  MISSING INPUT: {p.relative_to(ROOT)}", file=sys.stderr)
        return None
    return json.loads(p.read_text())


def ci(d, key="value_pts", lo="ci_lo", hi="ci_hi", star=True, prec=2):
    """A point estimate with its interval, bolded when it excludes zero."""
    if d is None:
        return PENDING
    v, l, h = d.get(key), d.get(lo), d.get(hi)
    if v is None:
        return PENDING
    body = f"${v:+.{prec}f}$ \\tiny[{l:+.{prec}f}, {h:+.{prec}f}]"
    sig = d.get("excludes_zero")
    if sig is None:
        sig = (l is not None and h is not None and (l > 0 or h < 0))
    return f"\\textbf{{{body}}}" if (star and sig) else body


def write(name: str, body: str, source: str, caption: str, label: str):
    hdr = (f"% GENERATED by scripts/paper/gen_tables.py on "
           f"{dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}\n"
           f"% SOURCE: {source}\n"
           f"% Do not edit by hand -- regenerate. Numbers come from result files, never from a report.\n")
    (OUT / name).write_text(hdr + body)
    print(f"  wrote paper/tables/{name}")


